// Copies the bundled fonts (OFL licensed) into static/fonts so the app works fully offline.
import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
const fonts = [
  ["atkinson-hyperlegible", "Atkinson Hyperlegible", ["400-normal", "700-normal", "400-italic"]],
  ["literata", "Literata", ["400-normal", "700-normal", "400-italic"]],
  ["opendyslexic", "OpenDyslexic", ["400-normal", "700-normal"]],
  // the comics themes' headings (styles.css Part twenty-eight); never the reading text
  ["bangers", "Bangers", ["400-normal"]],
  ["dela-gothic-one", "Dela Gothic One", ["400-normal"]],
];
mkdirSync("static/fonts", { recursive: true });
let css = "/* Generated by scripts/copy-fonts.mjs — fonts are SIL Open Font License */\n";
for (const [pkg, family, variants] of fonts) {
  for (const v of variants) {
    const file = `${pkg}-latin-${v}.woff2`;
    copyFileSync(`node_modules/@fontsource/${pkg}/files/${file}`, `static/fonts/${file}`);
    const [weight, style] = v.split("-");
    css += `@font-face{font-family:"${family}";font-style:${style};font-weight:${weight};font-display:swap;src:url(/static/fonts/${file}) format("woff2")}\n`;
  }
}
writeFileSync("static/fonts.css", css);
console.log("fonts copied");

// KaTeX (MIT): its stylesheet and math fonts, served locally for offline math rendering.
mkdirSync("static/katex/fonts", { recursive: true });
copyFileSync("node_modules/katex/dist/katex.min.css", "static/katex/katex.min.css");
for (const f of readdirSync("node_modules/katex/dist/fonts")) {
  if (f.endsWith(".woff2")) copyFileSync(`node_modules/katex/dist/fonts/${f}`, `static/katex/fonts/${f}`);
}
console.log("katex copied");
